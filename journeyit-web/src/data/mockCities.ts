// ─── Helper Functions ──────────────────────────

export function getMockCity(cityName: string): CityData | undefined {
  const normalized = cityName.toLowerCase().trim();
  return MOCK_CITIES[normalized];
}

export function getAllMockCities(): CityData[] {
  return Object.values(MOCK_CITIES);
}

export function getMockHotelsForCity(cityName: string): MockHotel[] {
  const city = getMockCity(cityName);
  return city ? city.hotels : [];
}

export function getMockHotelSearchResult(cityName: string): {
  city: string;
  hotels: MockHotel[];
  source: string;
} {
  const city = getMockCity(cityName);
  if (city) {
    return {
      city: city.displayName,
      hotels: city.hotels,
      source: "mock_data",
    };
  }
  // Fallback: return a random city if city not found
  const randomCity = Object.values(MOCK_CITIES)[0];
  return {
    city: randomCity.displayName,
    hotels: randomCity.hotels,
    source: "mock_data_fallback",
  };
}

export function getCityCenter(cityName: string): { lat: number; lng: number } {
  const city = getMockCity(cityName);
  return city?.center || { lat: 20.5937, lng: 78.9629 }; // Default to India center
}

